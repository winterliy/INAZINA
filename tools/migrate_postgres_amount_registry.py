"""Copy the amount-field inventory from a migrated SQLite copy to PostgreSQL.

Usage: python tools/migrate_postgres_amount_registry.py COPY.db postgresql:///TARGET

The source must be an SQLite backup initialized by the current application.
Both inventory tables are copied in one PostgreSQL transaction; existing
PostgreSQL-only entries are kept and the migration can be run again.
"""
import sqlite3
import sys
from contextlib import closing
from pathlib import Path

import psycopg


def migrate(source_path, dsn):
    source_uri = Path(source_path).resolve().as_uri() + "?mode=ro"
    with closing(sqlite3.connect(source_uri, uri=True)) as source:
        registry = source.execute(
            "SELECT source_table,source_key_field,amount_field,currency_expression "
            "FROM financial_amount_field_registry"
        ).fetchall()
        exemptions = source.execute(
            "SELECT source_table,amount_field,reason FROM financial_amount_field_exemptions"
        ).fetchall()
    if not registry:
        raise ValueError("금액 필드 등록부가 비어 있습니다. 현재 코드로 초기화한 DB 사본을 사용해주세요.")
    with psycopg.connect(dsn) as target:
        target.execute("""CREATE TABLE IF NOT EXISTS financial_amount_field_registry (
            source_table TEXT NOT NULL, source_key_field TEXT NOT NULL,
            amount_field TEXT NOT NULL, currency_expression TEXT NOT NULL,
            PRIMARY KEY(source_table,source_key_field,amount_field),
            rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)""")
        target.execute("""CREATE TABLE IF NOT EXISTS financial_amount_field_exemptions (
            source_table TEXT NOT NULL, amount_field TEXT NOT NULL, reason TEXT NOT NULL,
            PRIMARY KEY(source_table,amount_field),
            rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)""")
        with target.cursor() as cursor:
            cursor.executemany(
                "INSERT INTO financial_amount_field_registry "
                "(source_table,source_key_field,amount_field,currency_expression) VALUES (%s,%s,%s,%s) "
                "ON CONFLICT(source_table,source_key_field,amount_field) DO UPDATE SET "
                "currency_expression=excluded.currency_expression", registry,
            )
            cursor.executemany(
                "INSERT INTO financial_amount_field_exemptions (source_table,amount_field,reason) "
                "VALUES (%s,%s,%s) ON CONFLICT(source_table,amount_field) DO UPDATE SET reason=excluded.reason",
                exemptions,
            )
    return len(registry), len(exemptions)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    fields, exemptions = migrate(sys.argv[1], sys.argv[2])
    print(f"금액 필드 {fields}개, 면제 {exemptions}개 이관 완료")
